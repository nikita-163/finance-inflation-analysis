-- ==========================================
-- Таблица банковских операций
-- ==========================================

-- 1. Совпадает ли количество строк с исходным файлом?
-- Ожидаемое значение: 555.

SELECT COUNT(*) AS total_rows
FROM finance.bank_transactions;

-- Факт: 555. Ожидание: 555.
-- Вывод: значения совпадают.

---------------------------------------------------------------

-- 2. Совпадает ли диапазон дат с исходным файлом?
-- Ожидаемое значение: первая операция — 24.06.2025, последняя — 22.06.2026.

SELECT 
    MIN(operation_date) AS min_date,
    MAX(operation_date) AS max_date
FROM finance.bank_transactions;

-- Факт: первая операция — 2025-06-24, последняя — 2026-06-22. Ожидание: первая операция — 24.06.2025, последняя — 22.06.2026.
-- Вывод: Даты совпадают.


-- ==========================================
-- Таблица макроэкономических показателей
-- ==========================================

-- 1. Совпадает ли количество строк с исходным файлом?
-- Ожидаемое значение: 12.

SELECT count(*)
FROM finance.inflation;

-- Факт: 12. Ожидание: 12.
-- Вывод: значения совпадают.

---------------------------------------------------------------

-- 2. Совпадает ли диапазон дат с исходным файлом?
-- Ожидаемое значение: первый период — 01.06.2025, последний — 01.05.2026.

SELECT MIN("period"),
MAX("period")
FROM finance.inflation;

-- Факт: первый период — 2025-06-01, последний — 2026-05-01. Ожидание: первый период — 01.06.2025, последний — 01.05.2026.
-- Вывод: Даты совпадают.


-- ==========================================
-- Находки, важные для дальнейшего анализа
-- ==========================================

-- Диапазон дат таблицы bank_transactions (2025-06-24 – 2026-06-22, 13 месяцев)
-- не совпадает с диапазоном таблицы inflation (2025-06-01 – 2026-05-01, 12 месяцев).
-- По транзакциям есть данные за июнь 2026, а данных по инфляции за этот месяц нет.
-- Это не ошибка импорта: обе таблицы соответствуют своим исходным файлам.